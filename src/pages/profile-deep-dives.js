export const PROFILE_DEPTH_PATHS = Object.keys(PROFILE_DEPTH_CONTENT);
export function renderProfileDepthPage(path,posts) {
  const e=s=>escapeHtml(String(s));
  const entry=PROFILE_DEPTH_CONTENT[path];
  if(!entry)return null;
  const sections=entry.sections.map(([heading,p1,p2],i)=>`<section class="prestige-section" aria-labelledby="d-${i}"><div class="prestige-section-head"><h2 id="d-${i}">${e(heading)}</h2></div><div class="prestige-prose"><p>${e(p1)}</p><p>${e(p2)}</p></div></section>`).join("\n");
  const refs=entry.sources.map(([name,url,note])=>`<a class="source-link" href="${e(url)}" target="_blank" rel="noopener noreferrer"><div><span>${e(name)}</span><small>${e(note)}</small></div><b aria-hidden="true">→</b></a>`).join("\n");
  const related=entry.related.map(([url,name])=>`<a class="editorial-card" href="${e(url)}"><span class="card-index">CONTINUE READING</span><h3>${e(name)}</h3><span class="card-link">EXPLORE →</span></a>`).join("\n");
  const pageContent=`${PAGE_BRAND_STYLES}<main class="content-page prestige-page"><article class="content-inner prestige-shell"><section class="prestige-hero"><div><span class="prestige-kicker">${e(entry.tag)}</span><h1>${e(entry.heading)}</h1><p class="prestige-deck">${e(entry.dek)}</p></div><aside class="prestige-summary"><div class="prestige-summary-head"><span>DEEP PROFILE</span><strong>Documented work and original sources</strong></div><div class="prestige-summary-row"><span>METHOD</span><strong>Dated publisher records</strong></div><div class="prestige-summary-row"><span>SCOPE</span><strong>Public professional record</strong></div></aside></section>${sections}<section class="prestige-section"><div class="prestige-section-head"><h2>Original references</h2><p>Check the published record.</p></div><div class="source-list">${refs}</div></section><section class="prestige-section"><div class="prestige-section-head"><h2>Explore related work</h2></div><div class="editorial-grid">${related}</div></section></article></main>`;
  return renderLayout({title:entry.title,description:entry.dek,canonical:`${SITE.domain}${path}`,posts,pageContent});
}
